/*
** gran_embed — встраивает файл (схему XSD, байт-код шейдера) в C++ как массив байтов.
** Вызов: gran_embed <входной файл> <выходной .cpp> <ИМЯ>. Выходной файл
** перезаписывается, только если его текст изменился: make не пересобирает лишнего.
**
** gran_embed embeds a file (an XSD schema, a shader byte code) into C++ as a byte array.
** Usage: gran_embed <input file> <output .cpp> <NAME>. The output file is rewritten
** only when its text has changed: make does not rebuild anything needlessly.
*/
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>

namespace
{
    // Сообщения инструмента сборки (на двух языках в одной строке)
    // The build tool messages (in two languages on one line)
    const char* const USAGE_TEXT = "использование / usage: gran_embed <input> <output.cpp> <NAME>";
    const char* const READ_FAILED_TEXT = "не удалось прочитать / cannot read: ";
    const char* const WRITE_FAILED_TEXT = "не удалось записать / cannot write: ";

    // Весь файл в строку; false — файл не открылся
    // The whole file into a string; false — the file did not open
    bool readWhole(const std::string& path, std::string& content)
    {
        std::ifstream input(path, std::ios::binary);
        std::ostringstream buffer;

        if (!input)
            return false;
        buffer << input.rdbuf();
        content = buffer.str();
        return true;
    }

    // Байты по 16 в строке; в конце — завершающий 0x00 (текст читается как строка)
    // Bytes 16 per line; a trailing 0x00 at the end (the text can be read as a string)
    void writeBytes(const std::string& data, std::ostringstream& out)
    {
        static const char HEX[] = "0123456789abcdef";

        for (std::size_t index = 0; index <= data.size(); ++index)
        {
            unsigned char byte = 0;
            if (index < data.size())
                byte = static_cast<unsigned char>(data[index]);
            if (index % 16 == 0)
                out << "\n        ";
            out << "0x" << HEX[byte >> 4] << HEX[byte & 0x0F] << ",";
        }
    }

    // Полный текст сгенерированного .cpp
    // The full text of the generated .cpp
    std::string generate(const std::string& source, const std::string& data, const std::string& name)
    {
        std::ostringstream out;

        out << "// Сгенерировано gran_embed из " << source << "; не править вручную\n"
            << "// Generated by gran_embed from " << source << "; do not edit by hand\n"
            << "#include <cstddef>\n\nnamespace gran::generated\n{\n"
            << "    extern const unsigned char " << name << "[];\n"
            << "    extern const std::size_t " << name << "_SIZE;\n\n"
            << "    const unsigned char " << name << "[] = {";
        writeBytes(data, out);
        out << "\n    };\n    const std::size_t " << name << "_SIZE = " << data.size() << ";\n}\n";
        return out.str();
    }
}

// Точка входа: 0 — готово, 1 — ошибка аргументов или файлов
// The entry point: 0 — done, 1 — an argument or file error
int main(int argc, char* argv[])
{
    std::string data;
    std::string previous;

    if (argc != 4)
    {
        std::cerr << USAGE_TEXT << '\n';
        return 1;
    }
    if (!readWhole(argv[1], data))
    {
        std::cerr << READ_FAILED_TEXT << argv[1] << '\n';
        return 1;
    }
    std::string text = generate(argv[1], data, argv[3]);
    if (readWhole(argv[2], previous) && previous == text)
        return 0;
    std::ofstream output(argv[2], std::ios::binary);
    output << text;
    if (!output)
    {
        std::cerr << WRITE_FAILED_TEXT << argv[2] << '\n';
        return 1;
    }
    return 0;
}
