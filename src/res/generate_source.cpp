#include "gran/res/manifest.hpp"
#include "gran/res/resources.hpp"
#include "gran/core/gran_exception.hpp"
#include "gran/core/i18n.hpp"

#include <cstdint>
#include <cstdio>
#include <sstream>

namespace gran::res
{
    namespace
    {
        // Файл пакета целиком; не прочитан — ошибка с путём / The whole bundle file; not read — an error with the path
        std::vector<std::uint8_t> readSource(const ManifestFile& file)
        {
            std::vector<std::uint8_t> bytes;

            if (!readFile(file.source, bytes))
                throw GranException(ErrorCode::RESOURCE, i18n::format(i18n::Message::RES_MISSING_FILE,
                    {file.source.u8string()}));
            return bytes;
        }

        // Байты по 16 в строке; пустой файл — один нулевой байт (массив C++ не бывает пустым) / Bytes 16 per line; an empty file is one zero byte (a C++ array cannot be empty)
        void appendBytes(std::ostringstream& out, const std::vector<std::uint8_t>& bytes)
        {
            char text[8];

            if (bytes.empty())
                out << "        0x00,\n";
            for (std::size_t index = 0; index < bytes.size(); ++index)
            {
                if (index % 16 == 0)
                    out << "        ";
                std::snprintf(text, sizeof(text), "0x%02x,", static_cast<unsigned>(bytes[index]));
                out << text;
                if (index % 16 == 15 || index + 1 == bytes.size())
                    out << '\n';
            }
        }

        // Массив одного файла: DATA_<номер> с путём в комментарии; размер файла / The array of one file: DATA_<number> with the path in a comment; the file size
        std::size_t appendFile(std::ostringstream& out, const ManifestFile& file, std::size_t index)
        {
            std::vector<std::uint8_t> bytes = readSource(file);

            out << "    // " << file.alias << "\n    const unsigned char DATA_" << index << "[] = {\n";
            appendBytes(out, bytes);
            out << "    };\n";
            return bytes.size();
        }
    }

    /*
    ** Сгенерированный .cpp: безымянное пространство с массивами и таблицей записей, наружу — только
    ** функция granResources_<имя>(). Пути — из схемы (только ASCII без кавычек), экранирование не нужно.
    **
    ** The generated .cpp: an unnamed namespace with the arrays and the entry table, outside — only
    ** the granResources_<name>() function. The paths come from the schema (ASCII only without quotes), no escaping is needed.
    */
    std::string generateSource(const Manifest& manifest)
    {
        std::ostringstream out;
        std::vector<std::size_t> sizes;

        out << "// Сгенерировано gran_rcc из " << manifest.location.filename().u8string() << ", не править.\n"
            << "// Generated by gran_rcc from " << manifest.location.filename().u8string() << ", do not edit.\n"
            << "#include \"gran/res/resources.hpp\"\n\nnamespace\n{\n";
        for (std::size_t index = 0; index < manifest.files.size(); ++index)
            sizes.push_back(appendFile(out, manifest.files[index], index));
        out << "    const gran::res::Entry ENTRIES[] = {\n";
        for (std::size_t index = 0; index < manifest.files.size(); ++index)
            out << "        {\"" << manifest.files[index].alias << "\", DATA_" << index << ", " << sizes[index] << "},\n";
        if (manifest.files.empty())
            out << "        {\"\", nullptr, 0},\n";
        out << "    };\n}\n\n// Пакет ресурсов " << manifest.name << " / The " << manifest.name << " resource bundle\n"
            << "const gran::res::Bundle& granResources_" << manifest.name << "()\n{\n"
            << "    static const gran::res::Bundle BUNDLE{\"" << manifest.name << "\", ENTRIES, " << manifest.files.size()
            << "};\n\n    return BUNDLE;\n}\n";
        return out.str();
    }
}
