#include "gran/markup/internal/components.hpp"

#include <string>

namespace gran::markup::internal
{
    namespace
    {
        // Значение атрибута XML: & < > " экранируются / An XML attribute value: & < > " are escaped
        std::string escapeXml(std::string_view text)
        {
            std::string result;

            for (char symbol : text)
            {
                if (symbol == '&')
                    result += "&amp;";
                else if (symbol == '<')
                    result += "&lt;";
                else if (symbol == '>')
                    result += "&gt;";
                else if (symbol == '"')
                    result += "&quot;";
                else
                    result += symbol;
            }
            return result;
        }

        /*
        ** Типы gran-ui.xsd (без пространства имён): у всех есть выражение {…}, поэтому экземпляр в теле
        ** другого компонента может передать дальше свой параметр (accent="{$accent}").
        **
        ** The gran-ui.xsd types (without a namespace): all of them have the {…} expression, so an instance in the body
        ** of another component can pass its own parameter further (accent="{$accent}").
        */
        const char* typeName(ParamType type) noexcept
        {
            static const char* const NAMES[] = {"xs:string", "Number", "BindableBoolean", "Color", "Paint", "Length", "Size", "Action"};

            return NAMES[static_cast<int>(type)];
        }

        // Атрибут-параметр; values — перечисление вместе с выражениями и токенами темы / A parameter attribute; values is an enumeration together with the expressions and theme tokens
        void writeParam(std::string& out, const ComponentParam& param)
        {
            out += "      <xs:attribute name=\"" + param.name + "\"";
            if (param.values.empty())
                out += std::string(" type=\"") + typeName(param.type) + "\"";
            if (param.required)
                out += " use=\"required\"";
            out += ">\n";
            if (param.defaultValue.has_value())
                out += "        <xs:annotation><xs:documentation>default: " + escapeXml(*param.defaultValue)
                    + "</xs:documentation></xs:annotation>\n";
            if (!param.values.empty())
            {
                out += "        <xs:simpleType><xs:union memberTypes=\"Binding TokenRef\"><xs:simpleType>"
                       "<xs:restriction base=\"xs:string\">";
                for (const std::string& value : param.values)
                    out += "<xs:enumeration value=\"" + escapeXml(value) + "\"/>";
                out += "</xs:restriction></xs:simpleType></xs:union></xs:simpleType>\n";
            }
            out += "      </xs:attribute>\n";
        }

        /*
        ** Элемент компонента: дети — элементы интерфейса, если в теле есть слоты (иначе экземпляр пуст);
        ** атрибуты — параметры и атрибуты хозяина (component_params.cpp: HOST_ATTRIBUTES и slot).
        **
        ** The component element: the children are UI elements if the body has slots (otherwise the instance is empty);
        ** the attributes are the parameters and the host attributes (component_params.cpp: HOST_ATTRIBUTES and slot).
        */
        void writeComponent(std::string& out, const ComponentSpec& spec)
        {
            out += "  <xs:element name=\"" + spec.name + "\">\n    <xs:complexType>\n";
            if (spec.defaultSlot || !spec.slots.empty())
                out += "      <xs:sequence><xs:group ref=\"UiElement\" minOccurs=\"0\" maxOccurs=\"unbounded\"/></xs:sequence>\n";
            for (const ComponentParam& param : spec.params)
                writeParam(out, param);
            out += "      <xs:attribute name=\"id\" type=\"xs:NCName\"/>\n"
                   "      <xs:attribute name=\"slot\" type=\"xs:NCName\"/>\n"
                   "      <xs:attribute name=\"visible\" type=\"BindableBoolean\"/>\n"
                   "      <xs:attribute name=\"enabled\" type=\"BindableBoolean\"/>\n"
                   "      <xs:attributeGroup ref=\"BoxAttributes\"/>\n"
                   "    </xs:complexType>\n  </xs:element>\n";
        }
    }

    // Импорт без адреса: типы gran-ui.xsd передаются в Schema::fromDocuments тем же вызовом / An import without a location: the gran-ui.xsd types are passed to Schema::fromDocuments in the same call
    std::string librarySchemaText(const ComponentSet& set, std::size_t library)
    {
        std::string out = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
                          "<!-- Сгенерировано Gran UI по <Library> / Generated by Gran UI from <Library> -->\n"
                          "<xs:schema xmlns:xs=\"http://www.w3.org/2001/XMLSchema\" targetNamespace=\"";

        out += escapeXml(set.libraries[library].namespaceUri) + "\" elementFormDefault=\"qualified\">\n  <xs:import/>\n";
        for (const ComponentSpec& spec : set.components)
        {
            if (spec.library == library)
                writeComponent(out, spec);
        }
        return out + "</xs:schema>\n";
    }
}
